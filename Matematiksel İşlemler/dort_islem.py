sayi_bir = int(input("Sayı giriniz : "))
sayi_iki = int(input("Sayı giriniz : "))

# Toplama
sonucTopla = sayi_bir+sayi_iki
print(f"Toplamın Sonucu : {sonucTopla}")

# Çıkar
sonucCikar = sayi_bir-sayi_iki
print(f"Çıkarmın Sonucu : {sonucCikar}")

# Çarpım
sonucCarp = sayi_bir*sayi_iki
print(f"Çarpımın Sonucu : {sonucCarp}")

# Bölüm
sonucBolum = sayi_bir/sayi_iki
print(f"Çarpımın Sonucu : {sonucBolum}")


